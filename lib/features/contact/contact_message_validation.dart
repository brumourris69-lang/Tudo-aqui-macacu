bool isValidBrazilianPhone(String value) {
  final digits = normalizeBrazilianPhone(value);
  if (digits.length != 10 && digits.length != 11) return false;
  if (!_validBrazilianAreaCodes.contains(digits.substring(0, 2))) return false;
  final subscriberNumber = digits.substring(2);
  return digits.length == 10
      ? RegExp(r'^[2-5][0-9]{7}$').hasMatch(subscriberNumber)
      : RegExp(r'^9[0-9]{8}$').hasMatch(subscriberNumber);
}
