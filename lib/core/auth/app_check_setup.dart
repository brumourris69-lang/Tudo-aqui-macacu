enum AppCheckMode { disabled, emulator, debugProvider, attestation }

AppCheckMode appCheckMode({
  required bool enabled,
  required bool emulator,
  required bool debug,
}) => !enabled
    ? AppCheckMode.disabled
    : emulator
    ? AppCheckMode.emulator
    : debug
    ? AppCheckMode.debugProvider
    : AppCheckMode.attestation;

/// Provider configuration for a future authorized real-device validation.
/// Emulator mode never activates a provider or exchanges an App Check token.
class AppCheckProviderPlan {
  const AppCheckProviderPlan(this.mode);
  final AppCheckMode mode;
  bool get activatesProvider =>
      mode == AppCheckMode.debugProvider || mode == AppCheckMode.attestation;
  AndroidProvider get android => mode == AppCheckMode.debugProvider
      ? AndroidProvider.debug
      : AndroidProvider.playIntegrity;
  AppleProvider get apple => mode == AppCheckMode.debugProvider
      ? AppleProvider.debug
      : AppleProvider.appAttestWithDeviceCheckFallback;
}

AppCheckProviderPlan stagingAppCheckPlan({
  required bool enabled,
  required bool debugBuild,
  required bool android,
}) {
  if (!enabled || !debugBuild || !android) {
    throw StateError(
      'App Check de homologação exige Android debug habilitado.',
    );
  }
  return const AppCheckProviderPlan(AppCheckMode.debugProvider);
}

/// Beta distribution uses platform attestation; debug tokens are never
/// accepted for this flavor.
AppCheckProviderPlan betaAppCheckPlan({
  required bool enabled,
  required bool appCheckEnabled,
  required bool android,
  bool ios = false,
  required String projectId,
}) {
  if (!enabled ||
      !appCheckEnabled ||
      android == ios ||
      !BetaEnvironment.isIsolatedFirebaseProject(projectId)) {
    throw StateError(
      'App Check do Beta exige Android ou iOS e um projeto isolado autorizado.',
    );
  }
  return const AppCheckProviderPlan(AppCheckMode.attestation);
}

AppCheckProviderPlan normalFirebaseDebugAppCheckPlan({
  required bool optIn,
  required bool debugBuild,
  required bool android,
  required String? projectId,
}) {
  if (!optIn || !debugBuild || !android || projectId != 'tudo-aqui-macacu') {
    throw StateError(
      'App Check de teste exige Android debug e o projeto Firebase autorizado.',
    );
  }
  return const AppCheckProviderPlan(AppCheckMode.debugProvider);
}

/// Injectable orchestration; SDK calls in tests are fakes, not attestation.
Future<void> prepareAppCheckProviders({
  required AppCheckProviderPlan plan,
  required Future<void> Function(AppCheckProviderPlan) activate,
  required Future<void> Function(bool) setAutoRefresh,
  bool activationAuthorized = false,
}) async {
  if (!plan.activatesProvider) return;
  if (!activationAuthorized) {
    throw StateError('App Check de produção ainda não autorizado.');
  }
  try {
    await activate(plan);
    // SDK owns token caching/renewal. Do not force-refresh on every request.
    await setAutoRefresh(true);
  } catch (error) {
    // No fallback to a debug provider or unprotected backend after a failure.
    throw BetaStartupDiagnosticException(
      BetaStartupStage.appCheck,
      betaStartupFailureCode(BetaStartupStage.appCheck, error),
    );
  }
}

class AppCheckSetup {
  static const enabled = bool.fromEnvironment('LOCAL_SEARCH_APP_CHECK');
  static const normalFirebaseDebugOptIn = bool.fromEnvironment(
    'NORMAL_FIREBASE_DEBUG_TEST',
  );

  /// Enables only platform attestation after the Beta's independent project,
  /// application, OAuth client and native identity pass the startup gate.
  static Future<void> prepareBeta() async {
    if (!BetaEnvironment.enabled) {
      throw StateError('App Check do Beta chamado fora da variante Beta.');
    }
    BetaEnvironment.requireReady();
    final projectId = Firebase.apps.isEmpty
        ? null
        : Firebase.app().options.projectId;
    final plan = betaAppCheckPlan(
      enabled: BetaEnvironment.enabled,
      appCheckEnabled: BetaEnvironment.appCheckEnabled,
      android: defaultTargetPlatform == TargetPlatform.android,
      ios: defaultTargetPlatform == TargetPlatform.iOS,
      projectId: projectId ?? '',
    );
    await prepareAppCheckProviders(
      plan: plan,
      activationAuthorized: true,
      activate: (plan) => FirebaseAppCheck.instance.activate(
        androidProvider: plan.android,
        appleProvider: plan.apple,
      ),
      setAutoRefresh: FirebaseAppCheck.instance.setTokenAutoRefreshEnabled,
    );
  }

  /// Staging uses only the Android debug provider in a stagingDebug build.
  /// The token is generated by the SDK and must be registered out of band in
  /// the staging Firebase console; no token or production fallback is bundled.
  static Future<void> prepareStaging() async {
    if (!StagingEnvironment.enabled || !StagingEnvironment.appCheckEnabled) {
      throw StateError('App Check de homologação não foi habilitado.');
    }
    StagingEnvironment.requireReady();
    if (!kDebugMode) {
      throw StateError('App Check de homologação exige uma build debug.');
    }
    await prepareAppCheckProviders(
      plan: stagingAppCheckPlan(
        enabled: StagingEnvironment.appCheckEnabled,
        debugBuild: kDebugMode,
        android: defaultTargetPlatform == TargetPlatform.android,
      ),
      activationAuthorized: true,
      activate: (plan) => FirebaseAppCheck.instance.activate(
        androidProvider: plan.android,
        appleProvider: plan.apple,
      ),
      setAutoRefresh: FirebaseAppCheck.instance.setTokenAutoRefreshEnabled,
    );
  }

  static Future<void> prepare() async {
    if (normalFirebaseDebugOptIn) {
      final projectId = Firebase.apps.isEmpty
          ? null
          : Firebase.app().options.projectId;
      final plan = normalFirebaseDebugAppCheckPlan(
        optIn: normalFirebaseDebugOptIn,
        debugBuild: kDebugMode,
        android: defaultTargetPlatform == TargetPlatform.android,
        projectId: projectId,
      );
      await prepareAppCheckProviders(
        plan: plan,
        activationAuthorized: true,
        activate: (plan) => FirebaseAppCheck.instance.activate(
          androidProvider: plan.android,
          appleProvider: plan.apple,
        ),
        setAutoRefresh: FirebaseAppCheck.instance.setTokenAutoRefreshEnabled,
      );
      return;
    }
    final mode = appCheckMode(
      enabled: enabled,
      emulator: LocalSearchEnvironment.enabled,
      debug: kDebugMode,
    );
    await prepareAppCheckProviders(
      plan: AppCheckProviderPlan(mode),
      // Security 2D prepares the integration; no real activation is authorized.
      activationAuthorized: false,
      activate: (plan) => FirebaseAppCheck.instance.activate(
        androidProvider: plan.android,
        appleProvider: plan.apple,
      ),
      setAutoRefresh: (enabled) =>
          FirebaseAppCheck.instance.setTokenAutoRefreshEnabled(enabled),
    );
  }
}
